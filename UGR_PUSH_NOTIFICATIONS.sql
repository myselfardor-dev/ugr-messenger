-- UGR MESSENGER: push subscriptions
-- Run once in Supabase SQL Editor.
CREATE TABLE IF NOT EXISTS public.ugr_push_subscriptions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid NOT NULL REFERENCES auth.users(id) ON DELETE CASCADE,
  endpoint text NOT NULL UNIQUE,
  subscription jsonb NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS ugr_push_subscriptions_user_id_idx
  ON public.ugr_push_subscriptions(user_id);
ALTER TABLE public.ugr_push_subscriptions ENABLE ROW LEVEL SECURITY;
DROP POLICY IF EXISTS "Users manage own push subscriptions" ON public.ugr_push_subscriptions;
CREATE POLICY "Users manage own push subscriptions"
  ON public.ugr_push_subscriptions
  FOR ALL TO authenticated
  USING (user_id = auth.uid())
  WITH CHECK (user_id = auth.uid());
GRANT SELECT, INSERT, UPDATE, DELETE ON public.ugr_push_subscriptions TO authenticated;
GRANT USAGE, SELECT ON SEQUENCE public.ugr_push_subscriptions_id_seq TO authenticated;
